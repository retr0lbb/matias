export type AsaasBillingType = "UNDEFINED" | "BOLETO" | "CREDIT_CARD" | "PIX";

export type AsaasCycle =
	| "WEEKLY"
	| "BIWEEKLY"
	| "MONTHLY"
	| "BIMONTHLY"
	| "QUARTERLY"
	| "SEMIANNUALLY"
	| "YEARLY";

/** Discount Asaas grants to charges paid early enough. */
export interface AsaasDiscount {
	/** Percent (10 = 10%) or an amount in BRL, depending on `type`. */
	value: number;
	/** Days before the due date until which the discount holds; 0 = until the due date. */
	dueDateLimitDays: number;
	type: "FIXED" | "PERCENTAGE";
}

export interface UpdateAsaasSubscriptionInput {
	/** A discount with `value: 0` removes the current one. */
	discount?: AsaasDiscount;
	/** Also applies the change to charges already generated and not yet paid. */
	updatePendingPayments?: boolean;
	/** `INACTIVE` pauses the subscription on Asaas without deleting it. */
	status?: "ACTIVE" | "INACTIVE";
}

export interface CreateAsaasSubscriptionInput {
	/** Asaas customer id (`cus_...`). */
	customer: string;
	/** `UNDEFINED` lets the payer choose the method on the Asaas invoice. */
	billingType: AsaasBillingType;
	/** Amount per cycle in BRL (e.g. 29.9), not cents. */
	value: number;
	/** Due date of the first payment, `YYYY-MM-DD`. */
	nextDueDate: string;
	cycle: AsaasCycle;
	description?: string;
	/** Applied by Asaas to every charge until it is removed. */
	discount?: AsaasDiscount;
	/** Identifier of the subscription in our system. */
	externalReference?: string;
}

/** A single charge generated by a subscription. */
export interface AsaasPayment {
	object: "payment";
	/** Asaas payment id, e.g. `pay_080225913252`. */
	id: string;
	customer: string;
	/** Asaas subscription id (`sub_...`) the charge belongs to. */
	subscription?: string | null;
	/** Inherited from the subscription's `externalReference`. */
	externalReference?: string | null;
	status: string;
	billingType: string;
	value: number;
	dueDate: string;
	/** Hosted Asaas page where the payer completes the payment. */
	invoiceUrl: string;
}

export interface AsaasSubscription {
	object: "subscription";
	/** Asaas subscription id, e.g. `sub_VXJBYgP2u0eO`. */
	id: string;
	dateCreated: string;
	customer: string;
	billingType: string;
	cycle: AsaasCycle;
	value: number;
	nextDueDate: string;
	status: "ACTIVE" | "EXPIRED" | "INACTIVE";
	description?: string | null;
	externalReference?: string | null;
	deleted: boolean;
}
