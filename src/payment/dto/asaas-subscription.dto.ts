export type AsaasBillingType = "UNDEFINED" | "BOLETO" | "CREDIT_CARD" | "PIX";

export type AsaasCycle =
	| "WEEKLY"
	| "BIWEEKLY"
	| "MONTHLY"
	| "BIMONTHLY"
	| "QUARTERLY"
	| "SEMIANNUALLY"
	| "YEARLY";

export interface CreateAsaasSubscriptionInput {
	/** Asaas customer id (`cus_...`). */
	customer: string;
	/** `UNDEFINED` lets the payer choose the method on the Asaas invoice. */
	billingType: AsaasBillingType;
	/** Amount per cycle in BRL (e.g. 29.9), not cents. */
	value: number;
	/** Due date of the first payment, `YYYY-MM-DD`. */
	nextDueDate: string;
	cycle: AsaasCycle;
	description?: string;
	/** Identifier of the subscription in our system. */
	externalReference?: string;
}

/** A single charge generated by a subscription. */
export interface AsaasPayment {
	object: "payment";
	/** Asaas payment id, e.g. `pay_080225913252`. */
	id: string;
	customer: string;
	/** Asaas subscription id (`sub_...`) the charge belongs to. */
	subscription?: string | null;
	/** Inherited from the subscription's `externalReference`. */
	externalReference?: string | null;
	status: string;
	billingType: string;
	value: number;
	dueDate: string;
	/** Hosted Asaas page where the payer completes the payment. */
	invoiceUrl: string;
}

export interface AsaasSubscription {
	object: "subscription";
	/** Asaas subscription id, e.g. `sub_VXJBYgP2u0eO`. */
	id: string;
	dateCreated: string;
	customer: string;
	billingType: string;
	cycle: AsaasCycle;
	value: number;
	nextDueDate: string;
	status: "ACTIVE" | "EXPIRED" | "INACTIVE";
	description?: string | null;
	externalReference?: string | null;
	deleted: boolean;
}
